for (const width of [430, 1440]) test(`session commands do not shift the composer at ${width}px`, async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await fixture(page)
  await page.setViewportSize({ width, height: 1050 })
  if (width === 430) await expect.poll(async () => (await page.locator('.chat-pane').boundingBox())?.x).toBe(0)
  const input = page.getByRole('textbox', { name: 'Write a prompt' })
  await input.fill('A normal prompt')
  const before = await input.boundingBox()
  for (const command of ['/effort ', '/models ', '/research-skill ']) {
    await input.fill(command)
    await expect(page.getByRole('listbox')).toHaveCount(0)
    expect(await input.boundingBox()).toEqual(before)
    await expect(page.locator('.chat-composer > p.chat-composer-feedback')).toHaveCount(0)
  }
})
test('/rename appears as a session control and reuses the native rename dialog without prompting the agent', async ({ page }) => {
  const submissions = await fixture(page), renames: unknown[] = []
  await page.route('**/api/sessions/ses_slash/rename', route => {
    renames.push(route.request().postDataJSON())
    return route.fulfill({ json: { title: 'Better title' } })
  })
  const input = page.getByRole('textbox', { name: 'Write a prompt' })
  await input.fill('/rename')
  await expect(page.getByRole('option', { name: /\/rename/ })).toBeVisible()
  await input.press('Tab')
  await input.press('Control+Enter')
  const dialog = page.getByRole('dialog', { name: 'Rename conversation' })
  await expect(dialog.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('Slash commands')
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(input).toHaveValue('/rename ')
  await input.fill('/rename Better title')
  await input.press('Control+Enter')
  await expect(dialog.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('Better title')
  await dialog.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(input).toHaveValue('')
  expect(renames).toEqual([{ title: 'Better title' }])
  expect(submissions).toHaveLength(0)
})
