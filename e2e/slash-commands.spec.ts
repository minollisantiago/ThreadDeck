import { expect, test, type Page } from '@playwright/test'
import { modelControls } from '../shared/slash'

const projectId = '100000000000000001', threadId = '100000000000000002'
async function fixture(page: Page) {
  const now = Date.now(), submissions: Record<string, unknown>[] = []
  let model = { providerID: 'openai', id: 'gpt-6.1-sol', variant: 'medium' }
  await page.route('**/api/events', route => route.abort())
  await page.route('**/api/snapshot', route => route.fulfill({ json: { health: 'connected', checkedAt: now, lastSuccessAt: now, attentionAvailable: true, inventoryLimited: false, message: null, projects: [{ id: projectId, name: 'ThreadDeck', directory: '/fixture/threaddeck', sessions: [{ id: 'ses_slash', threadId, projectId, guildId: '100000000000000099', title: 'Slash commands', status: 'input', agentCount: 0, updatedAt: now, responseAt: now, model }] }] } }))
  await page.route('**/api/chat/**', route => {
    const path = new URL(route.request().url()).pathname
    if (path.endsWith('/info')) return route.fulfill({ json: { protocol: 1, kimakiVersion: '1.4.0', actor: 'local-operator', capabilities: ['history', 'changes', 'prompt', 'queue', 'create', 'files', 'catalog', 'abort', 'project-catalog', 'initial-invocation', 'model-controls'] } })
    if (path.endsWith('/catalog')) return route.fulfill({ json: { entries: [...(path.includes('/threads/') ? modelControls : []), { kind: 'skill', name: 'research', description: 'Investigate primary sources' }, { kind: 'command', name: 'docs:find', description: 'Find MCP documentation' }, ...Array.from({ length: 30 }, (_, index) => ({ kind: 'command', name: `review-${index}`, description: 'Review project changes' }))] } })
    if (path.endsWith('/models')) return route.fulfill({ json: { current: model, models: [{ providerID: 'openai', id: 'gpt-6.1-sol', name: 'GPT-6.1 Sol', variants: ['low', 'medium', 'high'] }] } })
    if (path.endsWith('/changes')) return
    if (path.endsWith('/messages')) return route.fulfill({ json: { cursor: 'slash:0', before: null, stale: false, messages: [] } })
    if (path.endsWith('/submit')) {
      const input = route.request().postDataJSON(); submissions.push(input)
      if (input.kind === 'control') model = { ...model, variant: input.text.split(' ')[1] || 'default' }
      return route.fulfill({ status: 202, json: { id: input.requestId, state: 'accepted', messageIds: [], updatedAt: now } })
    }
    if (path.includes('/operations/')) return route.fulfill({ json: { id: path.split('/').at(-1), state: 'submitted', messageIds: [], updatedAt: now, threadId, sessionId: 'ses_created' } })
    return route.fulfill({ status: 404, json: { error: 'Unexpected fixture endpoint' } })
  })
  await page.goto('/')
  await page.locator('.chat-manager').getByRole('button', { name: 'Slash commands', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Write a prompt' })).toBeVisible()
  return submissions
}
test('slash picker searches the full catalog and inserts MCP and skill invocations without executing', async ({ page }) => {
  const submissions = await fixture(page)
  const input = page.getByRole('textbox', { name: 'Write a prompt' })
  await input.fill('/')
  await expect(page.getByRole('option')).toHaveCount(39)
  await page.screenshot({ path: 'artifacts/slash-picker.png' })
  await input.fill('/PRIMARY SOURCES')
  await expect(page.getByRole('option')).toHaveCount(1)
  await input.press('Enter')
  await expect(input).toHaveValue('/research-skill ')
  expect(submissions).toHaveLength(0)
  await input.fill('/docs')
  await page.getByRole('option').click()
  await expect(input).toHaveValue('/docs:find ')
  await input.press('End')
  await input.pressSequentially('react "server components"')
  await input.press('Control+Shift+Enter')
  await expect.poll(() => submissions.length).toBe(1)
  expect(submissions[0]).toMatchObject({ kind: 'command', name: 'docs:find', text: 'react "server components"', delivery: 'queue' })
})
test('models and effort open real pickers and submit durable controls rather than prompts', async ({ page }) => {
  const submissions = await fixture(page), input = page.getByRole('textbox', { name: 'Write a prompt' })
  await input.fill('/models')
  await input.press('Control+Enter')
  const dialog = page.getByRole('dialog', { name: 'Switch session model' })
  await expect(dialog.getByRole('button', { name: 'high', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'high', exact: true }).click()
  await page.screenshot({ path: 'artifacts/model-picker.png' })
  expect(submissions).toHaveLength(0)
  await dialog.getByRole('button', { name: 'Apply to session' }).click()
  await expect.poll(() => submissions.length).toBe(1)
  expect(submissions[0]).toMatchObject({ kind: 'control', name: 'models', text: 'openai/gpt-6.1-sol high', delivery: 'send' })
  await expect(page.getByRole('button', { name: 'Pending…', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeDisabled()
  await expect(page.locator('.chat-operation')).toHaveCount(0)
  await input.fill('/effort')
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled()
  await input.press('Control+Enter')
  const variants = page.getByRole('dialog', { name: 'Switch model variant' })
  await expect(variants.getByRole('button', { name: 'high', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await variants.getByRole('button', { name: 'Cancel' }).click()
  await expect(input).toHaveValue('/effort')
  expect(submissions).toHaveLength(1)
})
test('expanded editor completion respects Vim insert and normal modes', async ({ page }) => {
  const submissions = await fixture(page)
  await page.getByRole('button', { name: 'Expand composer', exact: true }).click()
  const editor = page.locator('.cm-content')
  await editor.click(); await page.keyboard.press('i'); await page.keyboard.type('/rsrch')
  await expect(page.getByRole('option')).toHaveCount(1)
  await page.keyboard.press('Enter')
  await expect(editor).toHaveText('/research-skill ')
  expect(submissions).toHaveLength(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('status', { name: 'Vim mode' })).toHaveText('NORMAL')
  await expect(editor).toBeFocused()
})
