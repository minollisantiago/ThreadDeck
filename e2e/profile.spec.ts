for (const width of [320, 564]) test(`identity buttons align and Discord ID help appears on hover at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.addInitScript(profile => localStorage.setItem('threaddeck:profile', JSON.stringify({ selection: profile.id, profile })), profile)
  await fixture(page)
  await page.getByRole('button', { name: 'Profile and preferences', exact: true }).click()
  const popup = page.getByRole('dialog', { name: 'Profile and preferences', exact: true })
  await popup.getByRole('button', { name: 'All preferences' }).click()
  const section = popup.getByRole('region', { name: 'Identity', exact: true })
  await expect(section.locator('form .profile-note')).toHaveCount(0)
  const input = (await section.getByLabel('Discord user ID', { exact: true }).boundingBox())!
  const load = (await section.getByRole('button', { name: 'Load profile' }).boundingBox())!
  const refresh = (await section.getByRole('button', { name: 'Refresh name & avatar' }).boundingBox())!
  const local = (await section.getByRole('button', { name: 'Use local profile' }).boundingBox())!
  const link = (await popup.getByRole('link', { name: 'View Discord profile' }).boundingBox())!
  expect(input.y).toBeCloseTo(load.y, 0)
  expect(input.height).toBeCloseTo(load.height, 0)
  if (width <= 360) expect(local.y).toBeGreaterThan(refresh.y)
  else expect(refresh.y).toBeCloseTo(local.y, 0)
  expect(refresh.height).toBeCloseTo(local.height, 0)
  expect(refresh.x).toBeCloseTo(input.x, 0)
  expect(local.x + local.width).toBeCloseTo(load.x + load.width, 0)
  expect(link.x).toBeCloseTo(input.x, 0)
  expect(link.x + link.width).toBeCloseTo(load.x + load.width, 0)
  const help = section.getByRole('button', { name: 'How to find your Discord user ID' })
  const tooltip = page.locator('.app-tooltip').filter({ hasText: 'Developer Mode' })
  await expect(tooltip).toBeHidden()
  await help.hover()
  await expect(tooltip).toBeVisible()
  await expect(tooltip).toContainText('Copy User ID')
  await expect(tooltip).toContainText('not message authorship')
  const helpBounds = (await tooltip.boundingBox())!
  expect(helpBounds.x).toBeGreaterThanOrEqual(0)
  expect(helpBounds.x + helpBounds.width).toBeLessThanOrEqual(width)
  await page.screenshot({ path: `artifacts/profile-id-help-${width}.png` })
  await page.mouse.move(0, 0)
  await help.blur()
  await expect(tooltip).toBeHidden()
  await help.focus()
  await expect(tooltip).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(section.getByLabel('Discord user ID', { exact: true })).toBeFocused()
  await expect(section.getByRole('alert')).toHaveCount(0)
})
