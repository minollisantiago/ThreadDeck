for (const width of [430, 1440]) test(`keyboard shortcuts open from app controls and restore focus at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1050 })
  await fixture(page)
  if (width === 430) await page.getByRole('button', { name: 'Toggle session sidebar' }).click()
  const menu = page.getByRole('button', { name: 'App controls', exact: true })
  await menu.click()
  await page.getByRole('button', { name: 'Keyboard shortcuts', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Keyboard shortcuts', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText('Ctrl / ⌘ P, then P')
  await expect(dialog).toContainText('interrupts a working turn')
  const keybindBounds = await dialog.boundingBox()
  await dialog.getByRole('button', { name: 'Commands & skills', exact: true }).click()
  await expect(dialog.getByText('/research-skill', { exact: true })).toBeVisible()
  await expect(dialog.getByText('/review', { exact: true })).toBeVisible()
  await expect(dialog).toContainText('Bot-management slash commands')
  await dialog.getByRole('searchbox', { name: 'Filter commands and skills' }).fill('primary sources')
  await expect(dialog.getByText('/research-skill', { exact: true })).toBeVisible()
  await expect(dialog.getByText('/review', { exact: true })).toHaveCount(0)
  await dialog.getByRole('searchbox', { name: 'Filter commands and skills' }).fill('no-such-command')
  await expect(dialog).toContainText('No matching commands or skills.')
  expect(await dialog.boundingBox()).toEqual(keybindBounds)
  await expect(page.locator('.appearance-controls')).not.toBeVisible()
  expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(menu).toBeFocused()
})
