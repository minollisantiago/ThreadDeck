test('command reference surfaces catalog failures and supports retry', async ({ page }) => {
  await fixture(page)
  let failed = true
  await page.route('**/api/chat/threads/*/catalog', route => route.fulfill({ status: failed ? 503 : 200, json: failed ? { code: 'unavailable', error: 'Catalog temporarily unavailable' } : { entries: [] } }))
  await page.getByRole('button', { name: 'App controls', exact: true }).click()
  await page.getByRole('button', { name: 'Keyboard shortcuts', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Keyboard shortcuts', exact: true })
  const keybindBounds = await dialog.boundingBox()
  await dialog.getByRole('button', { name: 'Commands & skills', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Catalog temporarily unavailable')
  expect(await dialog.boundingBox()).toEqual(keybindBounds)
  failed = false
  await dialog.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(dialog).toContainText('No commands or skills are available for this project.')
  expect(await dialog.boundingBox()).toEqual(keybindBounds)
})
